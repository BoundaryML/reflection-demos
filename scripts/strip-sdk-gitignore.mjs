// `baml-dev generate` drops a `.gitignore` containing `*` into each generated
// sdk/client dir, which would silently untrack the committed clients. Delete
// them after every generate (wired into the root `pnpm generate` script).
import { readdirSync, readFileSync, unlinkSync, statSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)));

function walk(dir) {
  for (const entry of readdirSync(dir)) {
    if (entry === "node_modules" || entry === ".baml" || entry === "vendor") continue;
    const p = path.join(dir, entry);
    let st;
    try {
      st = statSync(p);
    } catch {
      continue; // dangling symlink etc.
    }
    if (!st.isDirectory()) continue;
    if (entry === "baml_sdk" || entry === "baml_client") {
      const gi = path.join(p, ".gitignore");
      try {
        // Generated form: an optional "# Generated by BAML" header, `*`, `!.gitignore`.
        const lines = readFileSync(gi, "utf8")
          .split("\n")
          .map((l) => l.trim())
          .filter((l) => l && !l.startsWith("#"));
        if (lines.length > 0 && lines.every((l) => l === "*" || l === "!.gitignore")) {
          unlinkSync(gi);
          console.log(`removed ${path.relative(root, gi)}`);
        }
      } catch {}
    }
    walk(p);
  }
}

walk(root);
